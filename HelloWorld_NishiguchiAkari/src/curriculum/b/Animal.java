package curriculum.b;

public class Animal {

	private String name;
	private double length;
	private int speed;
	
	public void setName(String name) {
		this.name = name;
	}
	public String getName() {
		return name;
	}
	
	
	public void setLength(double length) {
		this.length = length;
	}
	public double getLength() {
		return length;
	}
	
	
	public void setSpeed(int speed) {
		this.speed = speed;
	}
	public int getSpeed() {
		return speed;
	}
	
	
	

}
